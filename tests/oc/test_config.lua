-- The agent's config file: defaults, checks and the watchlist (WO-7.2).
local T = require("testlib")
local F = require("fakeoc")

local tests = {}
local function test(name, fn)
  tests[#tests + 1] = { name, fn }
end

local function load_with(text)
  local w = T.base({ config = text })
  local M = assert(F.load_agent(w))
  local cfg, err = M.load_config("/home/gos/gos-agent.cfg")
  return cfg, err
end

test("defaults", function()
  local cfg, err = load_with('{ token = "' .. T.TOKEN .. '" }')
  T.ok(cfg, err)
  T.eq(cfg.transport, "auto")
  T.eq(cfg.url, "http://127.0.0.1:8765/oc/telemetry")
  T.eq(cfg.cycle_s, 5, "power and machines every 5 s")
  T.eq(cfg.ae2_s, 60, "the AE2 watchlist every 60 s")
  T.eq(cfg.sensor_s, 60)
  T.eq(cfg.sensor_per_cycle, 2)
  T.eq(#cfg.watch, 0)
  T.eq(cfg.log_path, "/home/gos/gos-agent.log", "the log sits next to the config")
  T.eq(cfg.state_path, "/home/gos/gos-agent.state")
  T.ok(cfg.power_set["multimachine.supercapacitor"], "the LSC is read as storage")
end)

test("comments and the full example parse", function()
  local f = assert(io.open(F.ROOT .. "/oc/gos-agent.cfg.example", "rb"))
  local text = f:read("a")
  f:close()
  local cfg, err = load_with(text)
  T.no(cfg, "the example has no token yet, so it must not load as is")
  T.has(err, "token")
  cfg, err = load_with((text:gsub('token = "[^"]*"', 'token = "' .. T.TOKEN .. '"')))
  T.ok(cfg, err)
  T.eq(cfg.transport, "auto")
  T.ok(#cfg.watch >= 1, "the example watches something")
end)

test("unknown keys are refused", function()
  local cfg, err = load_with('{ token = "' .. T.TOKEN .. '", cylce_s = 5 }')
  T.no(cfg)
  T.has(err, "unknown config key cylce_s")
end)

test("cadence ranges", function()
  for _, bad in ipairs({ "cycle_s = 4", "cycle_s = 11", "ae2_s = 30", "sensor_per_cycle = 5", "sensor_per_cycle = 1.5",
    "sensor_s = 5", "request_timeout_s = 100", "reply_max = 100", "max_machines = 0" }) do
    local cfg, err = load_with('{ token = "' .. T.TOKEN .. '", ' .. bad .. " }")
    T.no(cfg, bad .. " was accepted")
    T.ok(err, "a reason for " .. bad)
  end
  local cfg, err = load_with('{ token = "' .. T.TOKEN .. '", cycle_s = 10, ae2_s = 120, sensor_per_cycle = 0 }')
  T.ok(cfg, err)
  T.eq(cfg.cycle_s, 10)
end)

test("token and url", function()
  local cfg, err = load_with('{ token = "short" }')
  T.no(cfg)
  T.has(err, "token")
  cfg, err = load_with('{ token = "has a space in it" }')
  T.no(cfg)
  T.has(err, "token")
  cfg, err = load_with('{ token = "' .. T.TOKEN .. '", url = "http://localhost:8765/oc/telemetry" }')
  T.no(cfg)
  T.has(err, "127.0.0.1")
  cfg, err = load_with('{ token = "' .. T.TOKEN .. '", url = "ftp://127.0.0.1/" }')
  T.no(cfg)
  T.has(err, "url")
  cfg, err = load_with('{ token = "' .. T.TOKEN .. '", url = "http://127.0.0.1:9000/oc/telemetry" }')
  T.ok(cfg, err)
end)

test("http needs a token", function()
  local w = T.base({ config = "{}" })
  local M = assert(F.load_agent(w))
  local cfg = assert(M.load_config("/home/gos/gos-agent.cfg"))
  local st = M.new_state(cfg, { out = function() end })
  local t, err = M.open_transport(st)
  T.no(t)
  T.has(err, "token")
end)

test("the watchlist uses registry names, never numeric ids", function()
  local function watch(entries)
    return load_with('{ token = "' .. T.TOKEN .. '", watch = { ' .. entries .. " } }")
  end
  local cfg, err = watch("{ id = 265, damage = 0 }")
  T.no(cfg)
  T.has(err, "never a numeric id")
  cfg, err = watch("{ name = 265, damage = 0 }")
  T.no(cfg)
  T.has(err, "never a numeric id")
  cfg, err = watch('{ name = "minecraft:iron_ingot" }')
  T.no(cfg, "damage is required")
  T.has(err, "damage")
  cfg, err = watch('{ name = "minecraft:iron_ingot", damage = 40000 }')
  T.no(cfg)
  T.has(err, "damage")
  cfg, err = watch('{ name = "minecraft:iron_ingot", damage = 1.5 }')
  T.no(cfg)
  cfg, err = watch('{ name = "iron ingot", damage = 0 }')
  T.no(cfg)
  T.has(err, "registry name")
  cfg, err = watch('{ name = "minecraft:iron_ingot", damage = 0, nbt = "{}" }')
  T.no(cfg)
  T.has(err, "unknown key nbt")
  cfg, err = watch('{ name = "gregtech:gt.metaitem.01", damage = 11305 }, { name = "gregtech:gt.metaitem.01", damage = 2305 }, '
    .. '{ name = "gregtech:gt.metaitem.01", damage = 11305 }, { name = "minecraft:iron_ingot", damage = 0 }')
  T.ok(cfg, err)
  T.eq(#cfg.watch, 3, "a duplicate entry counts once")
  T.eq(#cfg.watch_groups, 2, "one getItemsInNetworkById per distinct registry name")
  T.eq(cfg.watch_groups[1].name, "gregtech:gt.metaitem.01")
  T.ok(cfg.watch_groups[1].damages[11305] and cfg.watch_groups[1].damages[2305])
  local many = {}
  for i = 1, 65 do
    many[i] = ('{ name = "minecraft:stone", damage = %d }'):format(i)
  end
  cfg, err = watch(table.concat(many, ", "))
  T.no(cfg, "max_watch caps the list")
  T.has(err, "max_watch")
end)

test("the config can't run code", function()
  local cfg, err = load_with('{ token = os.getenv("TOKEN") }')
  T.no(cfg)
  T.has(err, "config")
  cfg, err = load_with('{ token = string.rep("a", 10) }')
  T.no(cfg, "the config's environment is empty")
  T.has(err, "string")
end)

test("a missing or broken file says what to do", function()
  local w = T.base({ no_config = true })
  local M = assert(F.load_agent(w))
  local cfg, err = M.load_config("/home/gos/gos-agent.cfg")
  T.no(cfg)
  T.has(err, "gos-agent.cfg.example")
  cfg, err = load_with("{ token = ")
  T.no(cfg)
  T.has(err, "config")
  cfg, err = load_with("42")
  T.no(cfg)
  T.has(err, "one Lua table")
end)

test("log and state can be moved or turned off", function()
  local cfg = assert(load_with('{ token = "' .. T.TOKEN .. '", log = false, state = "/var/gos.state" }'))
  T.eq(cfg.log_path, nil)
  T.eq(cfg.state_path, "/var/gos.state")
end)

return tests
