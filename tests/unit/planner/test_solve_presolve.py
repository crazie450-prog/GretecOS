def solve_model(options: dict[str, object]) -> tuple[int, bool]:
    """HiGHS's status and whether it gave a solution, as :func:`solve._solve` calls it."""
    c = np.zeros(N)
    for k, v in OBJECTIVE.items():
        c[k] = v
    ri: list[int] = []
    ci: list[int] = []
    vals: list[float] = []
    for i, (coefs, _, _) in enumerate(ROWS):
        for k in sorted(coefs):
            ri.append(i)
            ci.append(k)
            vals.append(coefs[k])
    a = coo_array((vals, (ri, ci)), shape=(len(ROWS), N)).tocsr()
    res = milp(
        c,
        constraints=[LinearConstraint(a, [r[1] for r in ROWS], [r[2] for r in ROWS])],
        integrality=np.array(INTEGRAL),
        bounds=Bounds(np.array(LB), np.array(UB)),
        options={**options, "time_limit": solve.TIME_LIMIT_S},
    )
    return int(res.status), res.x is not None


def test_presolve_is_off() -> None:
    assert solve._OPTIONS["presolve"] is False, "D245: see this file's docstring"
    assert solve._OPTIONS["mip_rel_gap"] == 0.0


def test_the_model_that_aborted_presolve_solves_with_the_solver_options() -> None:
    child = subprocess.run(
        [sys.executable, __file__],
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=120,
        check=False,
    )
    assert child.returncode == 0, (child.returncode, child.stderr[-2000:])
    assert child.stdout.strip().splitlines()[-1] == "status 0 solution True"


if __name__ == "__main__":
    opts = dict(solve._OPTIONS)
    if sys.argv[1:] == ["presolve"]:  # by hand only: shows what D245 works around
        opts["presolve"] = True
    status, found = solve_model(opts)
    print(f"status {status} solution {found}", flush=True)
